-- MYSQL PORTAL DATABASE ONLY. Never execute against SQL Server.
CREATE TABLE IF NOT EXISTS vendor_bank_details (
  ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  VENDORID VARCHAR(12) NOT NULL UNIQUE,
  ACCVEN VARCHAR(50) NULL,
  ACCNAME VARCHAR(255) NULL,
  BANKID VARCHAR(20) NULL,
  SORTCDE VARCHAR(20) NULL,
  BRNCH VARCHAR(255) NULL,
  SWIFTCDE VARCHAR(20) NULL,
  TPIN VARCHAR(20) NULL,
  PURPOSE_CODE VARCHAR(8) NULL,
  SECTOR_CODE VARCHAR(8) NULL,
  PHYSICAL_ADDRESS JSON NULL,
  COUNTRY_OF_ORIGIN VARCHAR(100) NULL,
  EMAIL VARCHAR(255) NULL,
  PHONE_NUMBER VARCHAR(255) NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  deleted_at DATETIME NULL
) ENGINE=InnoDB;
